"""Weekly hypothesis pipeline: candidates are recorded (never applied), idempotent per
ISO week, auto-generated by the Friday learn job, and runnable from the CLI. Offline."""
import importlib.util
import sys
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd
import pytest

from stockmoney.desk import store
from stockmoney.desk.execution.ledger import ensure_schema as ledger_schema
from stockmoney.desk.learn import hypotheses, job, links, tables
from stockmoney.desk.run import ensure_schema as run_schema
from tests.desk.test_learn import make_bars

TODAY = "2026-03-27"  # a Friday, ISO week 2026-W13


@pytest.fixture
def con(tmp_path):
    with store.connect(tmp_path / "d.sqlite") as c:
        run_schema(c)
        ledger_schema(c)
        tables.ensure_schema(c)
        yield c


def _loss(con, tid, day, symptoms, pnl=-100.0):
    con.execute("INSERT INTO trade_postmortem (trade_id, symbol, strategy, exit_day, pnl, symptoms) VALUES (?,?,?,?,?,?)",
                (tid, "AAPL", "breakout", day, pnl, symptoms))


def _two_weeks_of_s2(con):
    _loss(con, "t0", "2026-03-27", "S2", -150.0)
    _loss(con, "t1", "2026-03-20", "S2", -100.0)


def test_two_consecutive_weeks_are_recorded_as_candidate(con):
    _two_weeks_of_s2(con)
    out = hypotheses.run(con, TODAY)
    row = con.execute("SELECT * FROM weekly_hypotheses").fetchall()
    assert len(row) == 1
    r = row[0]
    assert (r["week"], r["symptom"], r["label"], r["status"]) == ("2026-W13", "S2", "被洗出場", "candidate")
    assert (r["loss_this"], r["loss_prev"], r["n_this"], r["n_prev"]) == (-150.0, -100.0, 1, 1)
    assert "S2 被洗出場 連續兩週排在虧損前兩名" in out and "不改任何參數" in out


def test_single_week_or_s0_only_records_nothing(con):
    _loss(con, "t0", "2026-03-27", "S2")
    _loss(con, "t1", "2026-03-20", "S0")
    _loss(con, "t2", "2026-03-27", "S0")
    out = hypotheses.run(con, TODAY)
    assert con.execute("SELECT COUNT(*) FROM weekly_hypotheses").fetchone()[0] == 0
    assert "沒有候選" in out


def test_rerun_in_same_week_updates_instead_of_duplicating_and_keeps_status(con):
    _two_weeks_of_s2(con)
    hypotheses.run(con, TODAY)
    con.execute("UPDATE weekly_hypotheses SET status='shadowing'")
    _loss(con, "t2", "2026-03-26", "S2", -50.0)
    hypotheses.run(con, "2026-03-27")
    rows = con.execute("SELECT status, loss_this, n_this FROM weekly_hypotheses").fetchall()
    assert [(r["status"], r["loss_this"], r["n_this"]) for r in rows] == [("shadowing", -200.0, 2)]


def test_no_record_flag_writes_nothing(con):
    _two_weeks_of_s2(con)
    out = hypotheses.run(con, TODAY, record_rows=False)
    assert con.execute("SELECT COUNT(*) FROM weekly_hypotheses").fetchone()[0] == 0
    assert "S2 被洗出場" in out


def test_recording_changes_no_live_setting(con):
    _two_weeks_of_s2(con)
    before = (con.execute("SELECT COUNT(*) FROM param_changes").fetchone()[0],
              con.execute("SELECT COUNT(*) FROM settings").fetchone()[0])
    hypotheses.run(con, TODAY)
    after = (con.execute("SELECT COUNT(*) FROM param_changes").fetchone()[0],
             con.execute("SELECT COUNT(*) FROM settings").fetchone()[0])
    assert before == after


def test_history_lists_earlier_weeks_in_report(con):
    _two_weeks_of_s2(con)
    hypotheses.run(con, "2026-03-20")  # week 12 sees only one week with S2 in range -> nothing
    hypotheses.run(con, TODAY)
    _loss(con, "t3", "2026-04-03", "S2", -10.0)
    out = hypotheses.run(con, "2026-04-03", record_rows=False)
    assert "## 歷史候選" in out and "2026-W13 S2 被洗出場(candidate)" in out


def _friday_setup(con, monkeypatch, tmp_path, n):
    monkeypatch.setattr(job.notify, "send", lambda title, msg, priority=3, tags=None: True)
    monkeypatch.setattr(job, "OUT_DIR", tmp_path / "out")
    monkeypatch.setattr(links, "default_fetch", lambda url, timeout=0: (_ for _ in ()).throw(OSError("offline")))
    bars = make_bars(n)
    last = bars.dates[-1]
    for i, d in enumerate((last, last - pd.Timedelta(days=7))):
        _loss(con, f"j{i}", str(d.date()), "S2")
    now = datetime(last.year, last.month, last.day, 21, 15, tzinfo=timezone.utc)
    return bars, now


def test_friday_learn_job_records_the_weekly_hypothesis(con, monkeypatch, tmp_path):
    bars, now = _friday_setup(con, monkeypatch, tmp_path, 423)
    assert bars.dates[-1].weekday() == 4
    body = job.run(con, now, bars=bars, shadow_start=str(bars.dates[-200].date()), with_allocator=False)
    rows = con.execute("SELECT symptom, status FROM weekly_hypotheses").fetchall()
    assert [(r["symptom"], r["status"]) for r in rows] == [("S2", "candidate")]
    assert "本週候選假設" in body


def test_non_friday_learn_job_does_not_record(con, monkeypatch, tmp_path):
    bars, now = _friday_setup(con, monkeypatch, tmp_path, 422)
    assert bars.dates[-1].weekday() == 3
    job.run(con, now, bars=bars, shadow_start=str(bars.dates[-200].date()), with_allocator=False)
    assert con.execute("SELECT COUNT(*) FROM weekly_hypotheses").fetchone()[0] == 0


def _prescreen_row(con, recv):
    from stockmoney.desk.learn import prescreen

    it = prescreen.Item("m#idea#0", "m", "IDEA", "idea", "AAPL", "", recv)
    prescreen._store(con, it, {"model": "m", "relevant_p": 0.9, "actionable_p": 0.9, "risk_score": 0.0,
                               "risk_conf": 0.9}, "pass", "actionable")


def test_friday_learn_job_carries_the_prescreen_weekly_section(con, monkeypatch, tmp_path):
    bars, now = _friday_setup(con, monkeypatch, tmp_path, 423)
    _prescreen_row(con, now.isoformat())
    body = job.run(con, now, bars=bars, shadow_start=str(bars.dates[-200].date()), with_allocator=False)
    assert "## 情報預篩週報(Jev)" in body and "升級率" in body


def test_non_friday_learn_job_has_no_prescreen_weekly_section(con, monkeypatch, tmp_path):
    bars, now = _friday_setup(con, monkeypatch, tmp_path, 422)
    _prescreen_row(con, now.isoformat())
    body = job.run(con, now, bars=bars, shadow_start=str(bars.dates[-200].date()), with_allocator=False)
    assert "情報預篩週報" not in body


def test_hypotheses_module_does_not_import_execution_layers():
    src = Path(hypotheses.__file__).read_text()
    for banned in ("execution.alpaca", "execution.broker", "execution.risk", "RiskEngine", ".submit(", "make_broker"):
        assert banned not in src


def test_cli_hypotheses_command_records_and_lists(tmp_path, monkeypatch, capsys):
    with store.connect(tmp_path / "d.sqlite") as c:
        run_schema(c)
        tables.ensure_schema(c)
        _two_weeks_of_s2(c)
    real_connect = store.connect
    monkeypatch.setattr(store, "connect", lambda path=None: real_connect(tmp_path / "d.sqlite"))
    spec = importlib.util.spec_from_file_location("desk_learn_cli", Path(__file__).parents[2] / "scripts" / "desk_learn.py")
    cli = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(cli)
    monkeypatch.setattr(sys, "argv", ["desk_learn.py", "hypotheses", "--date", TODAY])
    assert cli.main() == 0
    assert "S2 被洗出場 連續兩週" in capsys.readouterr().out
    monkeypatch.setattr(sys, "argv", ["desk_learn.py", "hypotheses", "--list"])
    assert cli.main() == 0
    assert "2026-W13 S2 被洗出場 [candidate]" in capsys.readouterr().out
